export const LOCALES = { fa, ar, en };

// Default digit style per language.
const DEFAULT_DIGITS = { fa: 'persian', ar: 'arabic', en: 'latin' };

// Intl locale per digit style, for the clock.
export const DIGIT_LOCALES = { persian: 'fa-IR', arabic: 'ar-EG', latin: 'en-GB' };

/**
 * Resolves options into { lang, digits, t }:
 *   lang:   'fa' | 'ar' | 'en' (unknown → 'fa')
 *   digits: 'persian' | 'arabic' | 'latin'; `true` = the language default, `false` = 'latin'
 *   t(key, vars): string with {name} placeholders filled in
 */
export function resolveLocale( { lang, digits, labels } = {} ) {
	const code = LOCALES[ lang ] ? lang : 'fa';
	const style = digits === false ? 'latin'
		: [ 'persian', 'arabic', 'latin' ].includes( digits ) ? digits
		: DEFAULT_DIGITS[ code ];
	// Every UI key exists in all three tables; a missing key (e.g. reveal.js help text in English) stays as is.
	const table = { ...LOCALES[ code ], ...labels };
	const t = ( key, vars = {} ) => ( table[ key ] ?? key ).replace( /\{(\w+)\}/g, ( m, name ) => vars[ name ] ?? m );
	return { lang: code, digits: style, t };
}
